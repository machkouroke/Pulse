// Generates nlohmann::json to_json() overloads for every enum and struct in
// pulse_wire.hpp, so new upstream fields reach the MCP without hand edits.
//   node gen_wire_json.mjs <pulse_wire.hpp> <out.hpp>
// Rules: `bool has_x` guards the field right after it (omitted when false);
// empty strings and empty vectors are omitted; enums become snake_case names.
import fs from "node:fs";

const [, , input, output] = process.argv;
const src = fs.readFileSync(input, "utf8").replace(/\/\/.*$/gm, "");

const snake = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();

const enums = [...src.matchAll(/enum class (\w+)\s*:\s*\w+\s*\{([^}]*)\}/g)].map(
  ([, name, body]) => ({
    name,
    values: [...body.matchAll(/(\w+)\s*=/g)].map((m) => m[1]),
  }),
);

const structs = [...src.matchAll(/struct (\w+)\s*\{([^}]*)\};/g)]
  .filter(([, , body]) => !body.includes("std::variant"))
  .map(([, name, body]) => ({
    name,
    fields: [...body.matchAll(/^\s*([\w:<>, ]+?)\s+(\w+)\s*(?:=[^;]*)?;/gm)].map(
      (m) => m[2],
    ),
  }));

let out = `// Generated by gen_wire_json.mjs from pulse_wire.hpp. Do not edit.
#pragma once
#include <nlohmann/json.hpp>
#include "pulse_wire.hpp"

namespace pulse::ipc {

template <typename T>
inline void Put(nlohmann::json& j, const char* key, const T& value) {
  j[key] = value;
}
inline void Put(nlohmann::json& j, const char* key, const std::string& value) {
  if (!value.empty()) j[key] = value;
}
template <typename T>
inline void Put(nlohmann::json& j, const char* key, const std::vector<T>& value) {
  if (!value.empty()) j[key] = value;
}

`;

for (const e of enums) {
  const pairs = e.values.map((v) => `{${e.name}::${v}, "${snake(v)}"}`).join(", ");
  out += `NLOHMANN_JSON_SERIALIZE_ENUM(${e.name}, {${pairs}})\n`;
}
out += "\n";
for (const s of structs) {
  out += `inline void to_json(nlohmann::json& j, const ${s.name}& v);\n`;
}
// has_x guards field x, else the nearest field named x_* (the flag sits before
// or after it depending on the struct). A has_x with no such field stays a bool.
function guards(fields) {
  const guard = new Map(); // guarded field -> its has_ flag
  fields.forEach((f, i) => {
    if (!f.startsWith("has_")) return;
    const t = f.slice(4);
    const nearestPrefixed = fields
      .map((g, j) => ({ g, d: Math.abs(j - i) }))
      .filter(({ g }) => g.startsWith(`${t}_`) && !g.startsWith("has_"))
      .sort((a, b) => a.d - b.d)[0]?.g;
    const pick = fields.includes(t) ? t : nearestPrefixed;
    if (pick && !guard.has(pick)) guard.set(pick, f);
  });
  return guard;
}

for (const s of structs) {
  out += `\ninline void to_json(nlohmann::json& j, const ${s.name}& v) {\n  j = nlohmann::json::object();\n`;
  const guard = guards(s.fields);
  const flags = new Set(guard.values());
  for (const f of s.fields) {
    if (flags.has(f)) continue;
    out += guard.has(f)
      ? `  if (v.${guard.get(f)}) Put(j, "${f}", v.${f});\n`
      : `  Put(j, "${f}", v.${f});\n`;
  }
  out += "}\n";
}
out += "\n}  // namespace pulse::ipc\n";

fs.writeFileSync(output, out);
console.log(`gen_wire_json: ${enums.length} enums, ${structs.length} structs -> ${output}`);
